object EmojiShortcodeConverter {

    private val SHORTCODE_REGEX = Regex(":([a-z0-9_+-]+):")

    /**
     * Replaces every known `:shortcode:` in [text] with its unicode emoji. Returns the original
     * string unchanged when it is null/blank or contains no known shortcodes.
     */
