/**
 * Converts GitHub/gemoji-style `:shortcode:` tokens (e.g. `:smile:`) into their unicode emoji
 * equivalents. Unknown shortcodes are left untouched so they keep rendering as plain text.
 *
 * Kitsu serves content with literal `:shortcode:` tokens, so this conversion is applied on the
